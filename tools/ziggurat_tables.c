/* Prints sh/sysl/random/ziggurat_tables.sysl: the 256-layer ziggurat tables for the standard normal
 * and the standard exponential, by J. A. Doornik's construction (*An Improved Ziggurat Method to
 * Generate Normal Random Samples*, 2005) with his R and V for 256 layers.
 *
 *     clang -O2 tools/ziggurat_tables.c -o zt -lm
 *     ./zt > sh/sysl/random/ziggurat_tables.sysl
 *     ./zt c > bench/ziggurat.h          (the same tables for the C reference the benchmark times)
 *
 * The tables are generated here rather than by `const` functions in sysl because `real.exp()` and
 * `real.ln()` are the C library's and do not run while compiling (see README, Findings).
 */
#include <math.h>
#include <stdio.h>

static int c_mode;

#define C 256

static void normal(double x[C + 1], double f[C + 1]) {
    const double r = 3.6541528853610088, v = 0.00492867323399;
    double fr = exp(-0.5 * r * r);
    x[0] = v / fr;
    x[1] = r;
    x[C] = 0;
    for (int i = 2; i < C; i++) {
        x[i] = sqrt(-2 * log(v / x[i - 1] + fr));
        fr = exp(-0.5 * x[i] * x[i]);
    }
    for (int i = 0; i <= C; i++) f[i] = exp(-0.5 * x[i] * x[i]);
}

static void exponential(double x[C + 1], double f[C + 1]) {
    const double r = 7.69711747013104972, v = 0.0039496598225815571993;
    double fr = exp(-r);
    x[0] = v / fr;
    x[1] = r;
    x[C] = 0;
    for (int i = 2; i < C; i++) {
        x[i] = -log(v / x[i - 1] + fr);
        fr = exp(-x[i]);
    }
    for (int i = 0; i <= C; i++) f[i] = exp(-x[i]);
}

static void table(const char *name, const char *what, const double *t) {
    printf(c_mode ? "/* %s */\n" : "/** %s */\n", what);
    if (c_mode) printf("static const double %s[257] = {\n", name);
    else printf("private[random] val %s: [257]real = [\n", name);
    for (int i = 0; i <= C; i++) {
        printf("%s%.17e%s", i % 4 == 0 ? "    " : " ", t[i], i == C ? "" : ",");
        if (i % 4 == 3 || i == C) printf("\n");
    }
    printf(c_mode ? "};\n\n" : "]\n\n");
}

int main(int argc, char **argv) {
    double x[C + 1], f[C + 1];
    c_mode = argc > 1 && argv[1][0] == 'c';
    if (c_mode) {
        printf("/* Generated by tools/ziggurat_tables.c -- do not edit by hand. */\n\n");
        printf("#define ZIG_NORM_R %.17e\n#define ZIG_EXP_R %.17e\n\n", 3.6541528853610088, 7.69711747013104972);
    } else {
        printf("module sh.sysl.random\n@no_alloc\n\n");
        printf("// Generated by tools/ziggurat_tables.c -- do not edit by hand.\n\n");
        printf("/** Where the normal ziggurat's tail begins. */\nprivate[random] const ZIG_NORM_R: real = %.17e\n\n", 3.6541528853610088);
        printf("/** Where the exponential ziggurat's tail begins. */\nprivate[random] const ZIG_EXP_R: real = %.17e\n\n", 7.69711747013104972);
    }
    normal(x, f);
    table("ZIG_NORM_X", "The normal ziggurat's layer edges, widest (the base strip's equivalent width) first, 0 last.", x);
    table("ZIG_NORM_F", "exp(-x^2/2) at each edge.", f);
    exponential(x, f);
    table("ZIG_EXP_X", "The exponential ziggurat's layer edges.", x);
    table("ZIG_EXP_F", "exp(-x) at each edge.", f);
    return 0;
}
